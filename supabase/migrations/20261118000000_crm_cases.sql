  for select to authenticated
  using (
    (deleted_at is null or (select public.crm_is_admin()))
    and (
      public.crm_can_see(owner_id)
      or public.crm_can_see_record('account', account_id)
      or public.crm_can_see_record('contact', contact_id)
    )
  );

