  for insert to authenticated
  with check (
    (select public.crm_can_write()) and (select public.crm_has_permission('cases', 'create'))
    and public.crm_can_see(owner_id)
    and deleted_at is null
    and (account_id is null or public.crm_can_see_record('account', account_id))
    and (contact_id is null or public.crm_can_see_record('contact', contact_id))
  );

