-- ---------------------------------------------------------------------------
-- SLA and resolution rules. Runs after the meta trigger (z prefix), so
-- created_at / updated_at are already set when the window is stamped.
-- Short, single-row and transaction-local: no cross-row locks.
-- ---------------------------------------------------------------------------
create or replace function public.crm_case_rules()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_hours jsonb;
  v_target numeric;
  v_created timestamptz;
begin
  select value into v_hours
  from public.crm_settings where key = 'case_sla_hours';

  v_target := nullif(coalesce(v_hours ->> NEW.priority, ''), '')::numeric;
  if v_target is null or v_target <= 0 then
    v_target := 48;
  end if;
  v_created := coalesce(NEW.created_at, now());

  if TG_OP = 'INSERT'
     or NEW.created_at is distinct from OLD.created_at
     or NEW.priority is distinct from OLD.priority then
    NEW.sla_due_at := v_created + make_interval(hours => v_target::integer);
  end if;

  -- First response starts when a ticket leaves "new".
  if NEW.status <> 'new'
     and (TG_OP = 'INSERT' or NEW.status is distinct from OLD.status)
     and NEW.first_response_at is null then
    NEW.first_response_at := coalesce(NEW.updated_at, now());
  end if;

  if NEW.status in ('resolved', 'closed') and NEW.resolved_at is null then
    NEW.resolved_at := coalesce(NEW.updated_at, now());
  elsif NEW.status in ('new', 'working') then
    NEW.resolved_at := null;
  end if;

  if NEW.resolved_at is not null then
    NEW.resolution_minutes := greatest(
      0,
      floor(extract(epoch from (NEW.resolved_at - v_created)) / 60)::integer
    );
  else
    NEW.resolution_minutes := null;
  end if;

  return NEW;
end;
$$;

revoke all on function public.crm_case_rules() from public, anon, authenticated;

